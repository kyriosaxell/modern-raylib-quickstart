Obstacle::Obstacle(const Vector2 position) {
	this->position = position;

	for (size_t row = 0; row < grid.size(); ++row) {
		for (size_t column = 0; column < grid[0].size(); ++column) {
			// If the value is 1, then we determinate to draw ;)
			if (grid[row][column] == 1) {
				const float pos_x = position.x + column * 3;
				const float pos_y = position.y + row * 3;
				auto block = Block{{pos_x, pos_y}};
				blocks.push_back(block);
			}
		}
	}
}

void Obstacle::Draw() const {
	for (auto& block : blocks) {
		block.Draw();
	}
}